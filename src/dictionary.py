"""Build docs/data_dictionary.md from the dataset's own metadata.

Inputs: data/raw/columns.json (Socrata columns API) and the official
EMS_incident_dispatch_data_description.xlsx attachment.
"""

from __future__ import annotations

import json

import pandas as pd

from src.config import DOCS, LIFE_THREATENING_SEGMENTS, RAW

XLSX = RAW / "EMS_incident_dispatch_data_description.xlsx"

DERIVED = [
    (
        "call_handling_s",
        "incident_datetime → first_assignment_datetime. Time from the incident being created in "
        "the EMS dispatch system to the first unit being assigned. Equals DISPATCH_RESPONSE_SECONDS_QY. "
        "Includes any time the call was held because no unit was free.",
    ),
    (
        "dispatch_s",
        "first_assignment_datetime → first_activation_datetime. Time from assignment to the unit "
        "signalling it is en route.",
    ),
    ("travel_s", "first_activation_datetime → first_on_scene_datetime. Driving time from en route to on scene."),
    (
        "response_s",
        "incident_datetime → first_on_scene_datetime = call_handling_s + dispatch_s + travel_s. "
        "Equals INCIDENT_RESPONSE_SECONDS_QY.",
    ),
    ("life_threatening", f"initial_severity_level_code in {', '.join(LIFE_THREATENING_SEGMENTS)}."),
    ("modzcta", "Modified ZIP Code Tabulation Area the incident zip belongs to (from the MODZCTA 'zcta' list)."),
    ("rt_ok", "Row passes every response-time cleaning rule (see docs/data_quality.md)."),
]


def official() -> tuple[dict[str, str], pd.DataFrame, pd.DataFrame]:
    d = pd.read_excel(XLSX, sheet_name="EMS File Description", header=None).iloc[2:]
    desc = {}
    for _, r in d.iterrows():
        if pd.isna(r[0]):
            continue
        key = str(r[0]).replace("*", "").strip().lower()
        text = str(r[1]).strip()
        if pd.notna(r[2]) and str(r[2]).strip():
            text += " " + str(r[2]).strip()
        desc[key] = text
    disp = pd.read_excel(XLSX, sheet_name="Incident Dispositions", header=None).iloc[2:].dropna()
    calls = pd.read_excel(XLSX, sheet_name="Call Type Descriptions", header=None).iloc[1:].dropna()
    return desc, disp, calls


def main() -> None:
    cols = json.loads((RAW / "columns.json").read_text())
    meta = json.loads((RAW / "dataset_meta.json").read_text())
    desc, disp, calls = official()
    lines = [
        "# Data dictionary",
        "",
        f"**{meta['name']}** (NYC Open Data `76xm-jjuj`, FDNY). {meta.get('description', '').strip()}",
        "",
        "Field types come from the Socrata columns API; descriptions come from the dataset's official "
        "attachment `EMS_incident_dispatch_data_description.xlsx`. Generated by `src/dictionary.py`.",
        "",
        "## Source fields",
        "",
        "| Field | Type | Description |",
        "|---|---|---|",
    ]
    for c in cols:
        f = c["fieldName"]
        lines.append(f"| `{f}` | {c['dataTypeName']} | {desc.get(f, '(no official description)')} |")
    lines += [
        "",
        "## Derived fields (src/clean.py)",
        "",
        "| Field | Definition |",
        "|---|---|",
        *[f"| `{k}` | {v} |" for k, v in DERIVED],
        "",
        "## Response-time breakdown",
        "",
        "The dataset has no timestamp for when the 911 call was answered, so the breakdown starts when the "
        "incident is created in the EMS dispatch system. The three parts used everywhere in this project are:",
        "",
        "1. **Call handling**: incident created → first unit assigned (`call_handling_s`).",
        "2. **Dispatch**: unit assigned → unit en route (`dispatch_s`).",
        "3. **Travel**: unit en route → first unit on scene (`travel_s`).",
        "",
        "Note the dataset's own `incident_travel_tm_seconds_qy` runs from assignment to on scene, so it equals "
        "dispatch + travel here.",
        "",
        "## Severity and the life-threatening definition",
        "",
        "Severity codes are FDNY dispatch segments 1 (most urgent) to 8 (least). FDNY and the Mayor's "
        "Management Report treat segments 1-3 as life-threatening medical emergencies (for example "
        "cardiac arrest, choking, major asthma, difficulty breathing, stroke). This project defines a "
        f"life-threatening call as `initial_severity_level_code` in {{{', '.join(LIFE_THREATENING_SEGMENTS)}}}: "
        "the initial segment is what the dispatcher knew when choosing how fast to send a unit. "
        "`life_threatening_final` uses the final segment instead and is kept for sensitivity checks.",
        "",
        "## Incident disposition codes",
        "",
        "| Code | Description |",
        "|---|---|",
        *[f"| {r[0]} | {r[1]} |" for _, r in disp.iterrows()],
        "",
        f"## Call types ({len(calls)} codes)",
        "",
        "| Code | Description |",
        "|---|---|",
        *[f"| {r[0]} | {r[1]} |" for _, r in calls.iterrows()],
        "",
        "## Other sources",
        "",
        "- **MODZCTA** (`pri4-ifjk`): Modified ZIP Code Tabulation Area polygons. Field `zcta` lists the "
        "5-digit ZCTAs merged into each MODZCTA; used to map incident zips.",
        "- **Facilities Database** (`ji82-xba5`, NYC Planning): records with facility type AMBULANCE STATION or "
        "EMERGENCY MEDICAL STATION operated by FDNY are used as known EMS station locations.",
        "- **Open-Meteo historical archive**: hourly temperature (°C), precipitation (mm), snowfall (cm), "
        "relative humidity (%) and wind speed (km/h) at Central Park (40.78 N, 73.97 W), local time.",
        "",
    ]
    (DOCS / "data_dictionary.md").write_text("\n".join(lines))
    print(f"wrote {DOCS / 'data_dictionary.md'} ({len(cols)} fields, {len(calls)} call types)")


if __name__ == "__main__":
    main()
